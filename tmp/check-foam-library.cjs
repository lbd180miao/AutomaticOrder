const {chromium}=require('D:/Scripts/FrciblyK12/.venv/Lib/site-packages/playwright/driver/package');
const fs=require('fs');
const assert=require('assert');
(async()=>{
 const browser=await chromium.launch({headless:true});
 const page=await browser.newPage({viewport:{width:1440,height:1000}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.route('**/*',route=>route.request().method()==='GET'?route.continue():route.abort());
 await page.goto('http://127.0.0.1:8082/vision/recipes/');
 await page.locator('#foam-recipe-list .recipe-card').first().waitFor();
 fs.writeFileSync('tmp/recipe_management-check.js',await page.locator('script:not([src])').allTextContents().then(s=>s.join('\n')));
 const card=page.locator('#foam-recipe-list .recipe-card').first();
 assert.equal(await card.getAttribute('open'),null);
 await card.locator('summary').click();
 await card.getByRole('button',{name:'编辑参数'}).click();
 await page.locator('#recipe-edit-modal').waitFor({state:'visible'});
 assert.equal(await page.locator('#recipe-edit-modal .page-hint').count(),0);
 await page.locator('#recipe-edit-modal').getByRole('button',{name:'取消'}).click();
 await page.screenshot({path:'tmp/foam-library-updated.png',fullPage:true});
 const href=await card.getByRole('link',{name:'进入 2D 工作台'}).getAttribute('href');
 const id=new URL(href,'http://localhost').searchParams.get('recipe_id');
 await page.goto('http://127.0.0.1:8082'+href);
 await page.waitForFunction(id=>document.getElementById('foam-recipe-select')?.value===id,id);
 await page.goto('http://127.0.0.1:8082/vision/recipes/');
 await page.locator('#foam-recipe-list .recipe-card').first().waitFor();
 await page.setViewportSize({width:800,height:1000});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
 assert.deepEqual(errors,[]);
 console.log('PASS: collapsed cards, editor, exact workbench recipe, 800px layout, no JS errors');
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
